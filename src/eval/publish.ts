/**
 * The ratings.yaml publication protocol (PLAN.md §Evaluation, §Publication
 * protocol). The file is a *derived projection*: display and sharing only.
 * Baton never reads it back for routing — routing reads SQLite — so the only
 * thing that has to be true of it is that it honestly reflects some committed
 * state, and never an older one than what is already on disk.
 *
 * Two races, two answers:
 *
 * - **Torn write** — render into a temp file in the same directory and
 *   `rename(2)` over the target. Readers see the old file or the new one.
 * - **Stale write** — a slow publisher overwriting a newer render. Every
 *   ratings-affecting commit bumps `ratings_revision` in its own transaction,
 *   so the publisher (1) takes the publication lock, (2) reads revision *and*
 *   ratings **inside that same transaction**, and (3) renames only over a file
 *   whose embedded `source_revision` is older.
 *
 * - **Corrupted body** — the header still claims a revision the body no longer
 *   matches (a truncated write from an older Baton, a hand-edit, a bad disk).
 *   The header carries a `digest` of everything below it, so startup repair can
 *   tell "current" from "merely labelled current" and re-render.
 *
 * The lock is a dedicated settings row written under `BEGIN IMMEDIATE`. That
 * suffices because SQLite is single-writer per database and one database is one
 * scope: taking the write lock excludes every other publisher *and* every
 * grade/prior commit, so the revision read cannot be torn from the state read.
 * The transaction is held across the render and the rename, which is what makes
 * "snapshot, then rename" atomic with respect to other Baton processes; the
 * on-disk revision check then also covers renders computed outside the lock.
 */

export const RATINGS_FILE = "ratings.yaml";

export const GENERATED_HEADER =
  "# GENERATED by Baton — do not edit. Edit via seed_ratings or baton profile.";

/** Publisher-private: the row whose write takes the publication lock. */
const SETTING_PUBLISH_LOCK = "ratings_published_at";

/** No file, or a file with no parseable header, is older than any revision. */
export const NO_REVISION = -1;

export function ratingsPath(configDir: string): string {
  return join(configDir, RATINGS_FILE);
}

export interface PublishResult {
  /** False when the on-disk projection was already at or ahead of this render. */
  published: boolean;
  revision: number;
  path: string;
}

/** One rendered line of provenance: observed and prior never merged silently. */
export interface RatingRow extends EffectiveRating {
  /** 'seeded' | 'imported:<name>', or null when there is no prior. */
  priorSource: string | null;
}

export interface RatingsSnapshot {
  revision: number;
  profile: string | null;
  profileWeight: number;
  rows: RatingRow[];
}

/**
 * Publishes ratings.yaml. Everything from the state read to the rename happens
 * under the publication lock; the render is discarded if the file on disk
 * already carries this revision or a newer one.
 */
export function publishRatings(db: Database, configDir: string, now = nowIso()): PublishResult {
  return withPublicationLock(db, now, (snapshot) => ({
    published: commitRender(configDir, renderRatings(snapshot, now), snapshot.revision),
    revision: snapshot.revision,
    path: ratingsPath(configDir),
  }));
}

/**
 * Startup repair (PLAN.md: "Startup repairs a stale projection"). Republishes
 * whenever the file's revision differs from the store's — including the case
 * where the file is *ahead* (a restored database, a copied config dir), which
 * the normal older-only rule would otherwise refuse to correct.
 */
export function repairProjection(db: Database, configDir: string, now = nowIso()): PublishResult {
  return withPublicationLock(db, now, (snapshot) => {
    const onDisk = fileRevision(configDir);
    // A matching revision is only worth trusting if the body still matches the
    // digest it was published with: a corrupted file with an intact header is
    // exactly the case the older-only rule would leave broken forever.
    if (onDisk === snapshot.revision && projectionIntact(configDir)) {
      return { published: false, revision: snapshot.revision, path: ratingsPath(configDir) };
    }
    return {
      published: commitRender(configDir, renderRatings(snapshot, now), snapshot.revision, {
        force: onDisk >= snapshot.revision,
      }),
      revision: snapshot.revision,
      path: ratingsPath(configDir),
    };
  });
}

/**
 * BEGIN IMMEDIATE, stamp the lock row, snapshot the state, and run `fn` while
 * still holding the write lock — see the module note on why that ordering is
 * the whole protocol.
 */
function withPublicationLock<T>(
  db: Database,
  now: string,
  fn: (snapshot: RatingsSnapshot) => T,
): T {
  return withBusyRetry(() => {
    db.exec("BEGIN IMMEDIATE");
    try {
      db.query(
        "INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO UPDATE SET value = excluded.value",
      ).run(SETTING_PUBLISH_LOCK, now);
      const result = fn(snapshotRatings(db, now));
      db.exec("COMMIT");
      return result;
    } catch (err) {
      try {
        db.exec("ROLLBACK");
      } catch {
        // SQLite already rolled back; the original error is what matters.
      }
      throw err;
    }
  });
}

/** The state the projection is made of. Call inside the publication lock. */
export function snapshotRatings(db: Database, now = nowIso()): RatingsSnapshot {
  const sources = new Map(activePriors(db).map((p) => [key(p.model, p.category), p.source]));
  return {
    revision: revision(db),
    profile: activeProfile(db),
    profileWeight: profileWeight(db),
    rows: effectiveRatings(db, now).map((r) => ({
      ...r,
      priorSource: sources.get(key(r.model, r.category)) ?? null,
    })),
  };
}

function key(model: string, category: string): string {
  return `${model}\u0000${category}`;
}

/**
 * Hand-rendered YAML: stable key order, 2-space indent, and observed / prior /
 * blended kept as three visibly separate things. This is the user-facing view
 * of where a number came from, so honest provenance beats compactness.
 */
export function renderRatings(snapshot: RatingsSnapshot, now = nowIso()): string {
  const lines = [
    `profile: ${yamlValue(snapshot.profile)}`,
    `profile_weight: ${yamlValue(round(snapshot.profileWeight))}`,
    snapshot.rows.length === 0 ? "ratings: []" : "ratings:",
  ];

  for (const row of snapshot.rows) {
    lines.push(`  - model: ${yamlValue(row.model)}`, `    category: ${yamlValue(row.category)}`);
    if (row.observed === null) {
      lines.push("    observed: null");
    } else {
      lines.push(
        "    observed:",
        `      mean: ${yamlValue(round(row.observed))}`,
        `      n_eff: ${yamlValue(round(row.nEff))}`,
      );
    }
    if (row.prior === null) {
      lines.push("    prior: null");
    } else {
      lines.push(
        "    prior:",
        `      mean: ${yamlValue(round(row.prior))}`,
        `      weight: ${yamlValue(round(row.priorWeight))}`,
        `      source: ${yamlValue(row.priorSource)}`,
      );
    }
    lines.push(`    blended: ${yamlValue(row.blended === null ? null : round(row.blended))}`);
  }

  // The header is the leading run of `#` lines; everything after it — the blank
  // separator included — is the body the digest covers, so reader and writer
  // agree on the split without either having to count lines.
  const body = `\n${lines.join("\n")}\n`;
  const header = [
    GENERATED_HEADER,
    `# source_revision: ${snapshot.revision}`,
    `# generated_at: ${now}`,
    `# digest: ${digest(body)}`,
    "#",
    "# observed: your own graded runs, decayed (n_eff = how many observations they are worth)",
    "# prior:    the active profile's seeded or imported opinion, decayed from its own as_of",
    "# blended:  the two combined — what selection ranks on",
    '# category "" is the uncategorised default: work graded without a category.',
  ];
  return `${header.join("\n")}\n${body}`;
}

/** sha256 of everything below the header — the render's own checksum. */
function digest(body: string): string {
  return createHash("sha256").update(body).digest("hex");
}

const DIGEST = /^#\s*digest:\s*([0-9a-f]{64})\s*$/;

/**
 * Whether the file on disk is still the render its header claims. A projection
 * with no digest line predates this check (or was hand-written) and counts as
 * not intact, so repair re-renders it once and it carries one from then on.
 */
export function projectionIntact(configDir: string): boolean {
  const path = ratingsPath(configDir);
  if (!existsSync(path)) return false;
  let text: string;
  try {
    text = readFileSync(path, "utf8");
  } catch {
    return false;
  }
  const lines = text.split("\n");
  let claimed: string | null = null;
  let i = 0;
  for (; i < lines.length && lines[i]!.startsWith("#"); i++) {
    const match = DIGEST.exec(lines[i]!);
    if (match) claimed = match[1]!;
  }
  return claimed !== null && claimed === digest(lines.slice(i).join("\n"));
}

/** Display precision. Nothing reads these numbers back, so two decimals is plenty. */
function round(value: number): number {
  return Math.round(value * 100) / 100;
}

/**
 * Atomically installs a render, unless the file already carries `rev` or newer.
 * Separate from `publishRatings` so a render's revision and its landing are
 * testable independently — a render is a value, and an old one must not land.
 */
export function commitRender(
  configDir: string,
  text: string,
  rev: number,
  opts: { force?: boolean } = {},
): boolean {
  const path = ratingsPath(configDir);
  if (!opts.force && fileRevision(configDir) >= rev) return false;
  const tmp = `${path}.tmp-${process.pid}-${Date.now().toString(36)}`;
  try {
    writeFileSync(tmp, text, { mode: 0o600 });
    renameSync(tmp, path);
  } catch (err) {
    try {
      unlinkSync(tmp);
    } catch {
      // Never written, or already gone.
    }
    throw err;
  }
  return true;
}

/** The revision of the projection currently on disk, or NO_REVISION. */
export function fileRevision(configDir: string): number {
  const path = ratingsPath(configDir);
  if (!existsSync(path)) return NO_REVISION;
  try {
    return parseSourceRevision(readFileSync(path, "utf8"));
  } catch {
    // Unreadable or not text: it cannot be a projection we should preserve.
    return NO_REVISION;
  }
}

const SOURCE_REVISION = /^#\s*source_revision:\s*(-?\d+)\s*$/;

/**
 * Reads `source_revision` out of the generated header. Missing or unparseable
 * (a hand-edited or truncated file) counts as older than everything, so the
 * next publish repairs it.
 */
export function parseSourceRevision(text: string): number {
  for (const line of text.split("\n")) {
    if (!line.startsWith("#")) break; // Header only; the body is not a source of truth.
    const match = SOURCE_REVISION.exec(line);
    if (match) return Number.parseInt(match[1]!, 10);
  }
  return NO_REVISION;
}
